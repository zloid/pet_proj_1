"use strict";

const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const appDirectory = path.join(root, "apps", "gbemu");
const defaultOutput = path.join(root, "dist", "gbemu-web-ide.js");
const indexFile = "gbemu.roms.json";
const TEXT_CHUNK_SIZE = 512;
const BINARY_CHUNK_SIZE = 384;

function usage() {
  return [
    "Usage: node scripts/build-web-ide-installer.js [--rom path/to/game.gb] [--out path/to/installer.js]",
    "",
    "Creates one JavaScript file that can be pasted into the Espruino Web IDE.",
    "The optional ROM must be a DMG ROM that you are entitled to use.",
  ].join("\n");
}

function readAppFile(filename) {
  return fs.readFileSync(path.join(appDirectory, filename), "utf8");
}

function crc32(bytes) {
  let crc = 0xffffffff;

  for (let index = 0; index < bytes.length; index += 1) {
    crc ^= bytes[index];
    for (let bit = 0; bit < 8; bit += 1) {
      crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
    }
  }

  return (crc ^ 0xffffffff) >>> 0;
}

function mapperFrom(cartridgeType) {
  if (
    cartridgeType === 0x00 ||
    cartridgeType === 0x08 ||
    cartridgeType === 0x09
  ) {
    return "ROM ONLY";
  }
  if (
    cartridgeType === 0x01 ||
    cartridgeType === 0x02 ||
    cartridgeType === 0x03
  ) {
    return "MBC1";
  }
  if (cartridgeType === 0x05 || cartridgeType === 0x06) return "MBC2";
  if (cartridgeType >= 0x0f && cartridgeType <= 0x13) return "MBC3";
  if (cartridgeType >= 0x19 && cartridgeType <= 0x1e) return "MBC5";
  return undefined;
}

function titleFrom(bytes) {
  let title = "";

  for (let index = 0x134; index < 0x144; index += 1) {
    const value = bytes[index];
    if (!value) break;
    title += value >= 32 && value < 127 ? String.fromCharCode(value) : " ";
  }

  return title.trim() || "Untitled ROM";
}

function createRomEntry(bytes) {
  if (bytes.length < 0x150) throw new Error("Not a valid DMG ROM");
  if (bytes[0x143] !== 0 && bytes[0x143] !== 0x80) {
    throw new Error("CGB-only ROMs are unsupported");
  }

  const mapper = mapperFrom(bytes[0x147]);
  if (!mapper) {
    throw new Error(
      "Unsupported cartridge mapper 0x" + bytes[0x147].toString(16),
    );
  }

  const checksum = crc32(bytes).toString(16);
  return {
    title: titleFrom(bytes),
    file: "gbemu.rom." + checksum,
    mapper,
    crc: checksum,
    size: bytes.length,
  };
}

function iconBytes() {
  const icon = vm.runInNewContext(readAppFile("app-icon.js"), { Uint8Array });
  return Buffer.from(icon);
}

function writeChunk(name, expression, offset, totalSize) {
  let source =
    "Storage.write(" + JSON.stringify(name) + ", " + expression + ", " + offset;

  if (offset === 0) source += ", " + totalSize;
  return source + ");";
}

function writeText(name, value) {
  const lines = [];

  for (let offset = 0; offset < value.length; offset += TEXT_CHUNK_SIZE) {
    lines.push(
      writeChunk(
        name,
        JSON.stringify(value.slice(offset, offset + TEXT_CHUNK_SIZE)),
        offset,
        value.length,
      ),
    );
  }

  return lines;
}

function writeBinary(name, bytes) {
  const lines = [];

  for (let offset = 0; offset < bytes.length; offset += BINARY_CHUNK_SIZE) {
    const chunk = bytes.subarray(offset, offset + BINARY_CHUNK_SIZE);
    lines.push(
      writeChunk(
        name,
        "atob(" + JSON.stringify(chunk.toString("base64")) + ")",
        offset,
        bytes.length,
      ),
    );
  }

  return lines;
}

function writeExpression(name, expression) {
  return "Storage.write(" + JSON.stringify(name) + ", " + expression + ");";
}

function appInfo(metadata) {
  return {
    id: metadata.id,
    name: metadata.name,
    shortName: metadata.shortName,
    type: "app",
    src: "gbemu.app.js",
    icon: "gbemu.img",
    version: metadata.version,
  };
}

function buildInstaller(options = {}) {
  const metadata = JSON.parse(readAppFile("metadata.json"));
  const engine = readAppFile("gbemu.engine.js");
  const app = readAppFile("app.js");
  const lines = [
    "/* Generated by scripts/build-web-ide-installer.js */",
    'var Storage = require("Storage");',
    'print("GBEMU: installing...");',
    ...writeText("gbemu.engine", engine),
    ...writeText("gbemu.app.js", app),
    ...writeBinary("gbemu.img", iconBytes()),
    ...writeText("gbemu.info", JSON.stringify(appInfo(metadata))),
  ];

  if (options.romPath) {
    const bytes = fs.readFileSync(path.resolve(options.romPath));
    const entry = createRomEntry(bytes);

    lines.push(...writeBinary(entry.file, bytes));
    lines.push("var entry = " + JSON.stringify(entry) + ";");
    lines.push(
      "var roms = Storage.readJSON(" + JSON.stringify(indexFile) + ", 1);",
    );
    lines.push("if (!Array.isArray(roms)) roms = [];");
    lines.push(
      "roms = roms.filter(function (existing) { return existing.file !== entry.file; });",
    );
    lines.push("roms.push(entry);");
    lines.push(writeExpression(indexFile, "JSON.stringify(roms)"));
  }

  lines.push('print("GBEMU: starting...");');
  lines.push('load("gbemu.app.js");');
  lines.push("");
  return lines.join("\n");
}

function parseArguments(args) {
  const options = { output: defaultOutput };

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--help" || argument === "-h") return { help: true };
    if (argument === "--rom") {
      options.romPath = args[index + 1];
      index += 1;
    } else if (argument === "--out") {
      options.output = path.resolve(args[index + 1] || "");
      index += 1;
    } else {
      throw new Error("Unknown argument: " + argument);
    }

    if (!args[index]) throw new Error("Missing value for " + argument);
  }

  return options;
}

function main() {
  const options = parseArguments(process.argv.slice(2));
  if (options.help) {
    console.log(usage());
    return;
  }

  const installer = buildInstaller(options);
  fs.mkdirSync(path.dirname(options.output), { recursive: true });
  fs.writeFileSync(options.output, installer);
  console.log("Wrote " + path.relative(root, options.output));
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}

module.exports = {
  buildInstaller,
  createRomEntry,
  crc32,
  parseArguments,
};
